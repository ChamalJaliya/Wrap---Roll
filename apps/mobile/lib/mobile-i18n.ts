type I18nKey = keyof (typeof text)['en'];

export function t(language: MobileLanguage, key: I18nKey): string {
  return text[language][key] ?? text.en[key];
}

export function cartSubtitle(language: MobileLanguage, itemCount: number): string {
  if (itemCount <= 0) return t(language, 'cartSubtitleEmpty');
  const itemWord = itemCount === 1 ? t(language, 'itemOne') : t(language, 'itemMany');
  return `${itemCount} ${itemWord} ${t(language, 'readyForCheckout')}`;
}
